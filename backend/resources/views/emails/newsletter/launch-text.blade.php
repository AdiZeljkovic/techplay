THE NEW TECHPLAY IS LIVE

Your gaming life, now in one place.

We rebuilt TechPlay around the person using it. Your games, the hours behind
them, what you finished and what you thought of it — all of it now lives on one
profile that fills itself in as you play.

Open it: {{ $appUrl }}


WHAT CHANGED

* Your library, whole
  Steam, Xbox, PlayStation, GOG and Epic in one shelf, plus anything you add
  by hand. Link a store and the games arrive with the hours already on them.

* Hours counted for you
  Playtime is read on a schedule and offered as a session. Nothing is logged
  until you say so.

* XP, levels and twenty ranks
  Everything you do adds up, from Newcomer to Eternal.

* Achievements
  Sixty-seven of them, across your shelf, the community, and a few nobody has
  found yet.

* 332,000+ games
  A catalogue you can search, and add from directly.

* Release calendar
  What is coming, and a reminder for the ones you actually care about.

* Backlog advisor
  Too many games and no idea which one? It reads your shelf and picks.


PROFESSOR BUFFY

Our Discord bot posts every new article, tracks XP from the server, and will
happily tell you your backlog did not shrink while you were away.


This is not a finished product and we are not going to pretend otherwise. More
store integrations, deeper library tools and a proper community layer are next.
